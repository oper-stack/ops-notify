/**
 * Свой ли это проверочный адрес.
 *
 * Простым языком. `info+test@oper-stack.com` и `info@oper-stack.com` это один ящик: метку после
 * плюса ставим мы сами, и означает она прогон, а не покупателя. Настоящий человек с такой меткой
 * на наших же доменах не приходит никогда.
 *
 * Зачем. 15.09.2026 Максим прислал снимок Telegram, где восемь сообщений «отчёт отправлен» подряд
 * за шесть минут закрыли собой всё остальное, и все восемь были прогонами по своему же сайту.
 *
 * Правило, по которому теперь живём: **в Telegram уходит либо деньги, либо человек, либо
 * поломка.** Всё остальное в лог и в таблицу. Тревоги при этом остаются громкими и на прогонах:
 * сломавшаяся проверка это поломка, о ней знать надо.
 *
 * Тот же признак используется в `tidy-tests.mjs`, чтобы убирать проверочные письма из «Входящих».
 */
const OWN_MAILBOXES = ['info@oper-stack.com', 'billing@oper-stack.com', 'accounts@oper-stack.com', 'support@oper-stack.com'];

export function isOwnTest(addr) {
  const a = String(addr || '').toLowerCase();
  return /\+[^@]*@/.test(a) && OWN_MAILBOXES.includes(a.replace(/\+[^@]*@/, '@'));
}
