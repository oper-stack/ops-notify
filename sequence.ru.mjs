/**
 * Письма цепочки по-русски.
 *
 * Это не перевод английских писем слово в слово. Рынок другой: цены рублёвые, оплата идёт
 * счётом по СБП, а не мгновенной кассой, и сравнение с агентством считается в рублях.
 *
 * Письма про цену со скидкой здесь нет. На английском оно ведёт на скрытый тариф Whop,
 * который открывается по ссылке и закрывается через сутки. На русском мгновенной кассы нет:
 * человек оставляет заказ и получает счёт письмом. Обещать цену, которую нельзя взять одним
 * нажатием, значит обещать то, чего нет. Поэтому русская цепочка идёт 3, 4, 5, 6.
 */

import { button, emailShell } from './email-shell.mjs';

const SITE = 'https://oper-stack.ru';
